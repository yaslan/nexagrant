import type { TenantTx } from '@/lib/db';
import { taskCreateSchema, taskDoneSchema, type TaskCreateInput, type TaskDoneInput } from './schemas';

/** Deal tasks (NG-135 / F3): open tasks for the görevler screen and done/undone toggling. */

export async function listTasks(tx: TenantTx, tenantId: string, take = 200) {
  return tx.dealTask.findMany({
    where: { tenantId, deletedAt: null },
    orderBy: [{ doneAt: { sort: 'asc', nulls: 'first' } }, { dueAt: { sort: 'asc', nulls: 'last' } }, { id: 'asc' }],
    take,
    select: {
      id: true,
      title: true,
      dueAt: true,
      doneAt: true,
      autoGenerated: true,
      dealId: true,
      deal: { select: { title: true, organization: { select: { name: true } } } },
    },
  });
}

export async function createTask(tx: TenantTx, tenantId: string, rawInput: unknown) {
  const input: TaskCreateInput = taskCreateSchema.parse(rawInput);
  const deal = await tx.deal.findFirst({
    where: { id: input.dealId, tenantId, deletedAt: null },
    select: { id: true },
  });
  if (!deal) return null;
  return tx.dealTask.create({
    data: { tenantId, dealId: deal.id, title: input.title, dueAt: input.dueAt },
    select: { id: true },
  });
}

/** Sets or clears `doneAt`. Returns null when the task is not visible to this tenant. */
export async function setTaskDone(tx: TenantTx, tenantId: string, rawInput: unknown, now = new Date()) {
  const input: TaskDoneInput = taskDoneSchema.parse(rawInput);
  const task = await tx.dealTask.findFirst({
    where: { id: input.taskId, tenantId, deletedAt: null },
    select: { id: true },
  });
  if (!task) return null;
  return tx.dealTask.update({
    where: { id: task.id },
    data: { doneAt: input.done ? now : null },
    select: { id: true, doneAt: true },
  });
}
