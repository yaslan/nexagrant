async function sessionCookie(tenantId: string, userId: string, email: string): Promise<string> {
  return encode({
    token: { sub: userId, id: userId, email, tenantId, role: 'TENANT_OWNER' },
    secret: SECRET,
    salt: COOKIE_NAME,
    maxAge: 60 * 60,
  });
}

async function signIn(context: BrowserContext, tenantId: string, userId: string, email: string) {
  const value = await sessionCookie(tenantId, userId, email);
  await context.addCookies([{ name: COOKIE_NAME, value, url: BASE_URL }]);
  // The cookie banner is a full-screen alertdialog and swallows clicks.
  await context.addInitScript(() => {
    window.localStorage.setItem(
      'fabrika_cookie_consent',
      JSON.stringify({ necessary: true, analytics: true, marketing: true }),
    );
  });
}

const shot = (page: Page, name: string) => page.screenshot({ path: `${SHOTS}/${name}.png`, fullPage: true });

/** No horizontal page scroll at the current viewport. */
async function expectNoPageOverflow(page: Page) {
  const { scroll, inner } = await page.evaluate(() => ({
    scroll: document.documentElement.scrollWidth,
    inner: window.innerWidth,
  }));
  expect(scroll, `page is ${scroll}px wide at a ${inner}px viewport`).toBeLessThanOrEqual(inner);
}

