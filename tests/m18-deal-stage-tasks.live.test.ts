import { afterAll, beforeAll, describe, expect, test, vi } from 'vitest';

/**
 * NG-216 — a deal that enters a stage gets that stage's auto tasks (AUTO_TASK_RULES), in the
 * same transaction as the move. Real Postgres, real Prisma, the `fabrika_app` role
 * (NOBYPASSRLS), no mocks; fixtures and counts go through the owner role.
 */
const { rlsUrl: RLS_URL, ownerUrl: OWNER_URL } = await vi.hoisted(async () => {
  const { readFileSync, existsSync } = await import('node:fs');
  const { resolve } = await import('node:path');
  const path = resolve(process.cwd(), '.env');
  const read = (key: string): string | undefined => {
    if (!existsSync(path)) return undefined;
    for (const line of readFileSync(path, 'utf8').split('\n')) {
      const t = line.trim();
      const i = t.indexOf('=');
      if (i > 0 && t.slice(0, i) === key) return t.slice(i + 1).replace(/^["']|["']$/g, '') || undefined;
    }
    return undefined;
  };
  const ownerUrl = process.env.DATABASE_URL ?? read('DATABASE_URL');
  const rlsUrl = process.env.DATABASE_URL_RLS_TEST ?? read('DATABASE_URL_RLS_TEST');
  if (rlsUrl) process.env.DATABASE_URL = rlsUrl;
  return { rlsUrl, ownerUrl };
});

import type { DealStage } from '@prisma/client';
import { createDbClient, prisma, withTenant } from '@/lib/db';
import { DealTransitionError, moveDealStage } from '@/modules/m18/server/deals-repo';
import { assertRlsSubjectRole, requireRlsTestUrl, skipOrFailInCi } from './helpers/live-db-role';

const SUITE = 'm18 deal stage tasks test';
const admin = createDbClient(OWNER_URL ?? 'postgresql://localhost:5432/unset');
const HAS_DB =
  requireRlsTestUrl(RLS_URL, SUITE) !== undefined &&
  Boolean(OWNER_URL) &&
  (await admin.$queryRaw`SELECT 1`.then(() => true).catch(() => false));
if (RLS_URL && !OWNER_URL) skipOrFailInCi(SUITE, 'DATABASE_URL (owner connection) is not set', 'Provide DATABASE_URL for the fixture/owner connection.');
else if (RLS_URL && !HAS_DB) skipOrFailInCi(SUITE, 'Postgres is unreachable');
if (HAS_DB) await assertRlsSubjectRole(prisma, SUITE);

const RUN = Math.random().toString(36).slice(2, 10);
let tenantId = '';

async function dealAt(stage: DealStage, label: string): Promise<string> {
  const org = await admin.leadOrganization.create({ data: { tenantId, name: `NG216 ${label} ${RUN}` }, select: { id: true } });
  const deal = await admin.deal.create({
    data: { tenantId, organizationId: org.id, title: `NG216 ${label} ${RUN}`, stage },
    select: { id: true },
  });
  return deal.id;
}

const move = (dealId: string, to: DealStage, lostReason?: string) =>
  withTenant(tenantId, (tx) => moveDealStage(tx, tenantId, { dealId, to, lostReason }, null, 'tr'));

const tasksOf = (dealId: string) =>
  admin.dealTask.findMany({ where: { tenantId, dealId }, orderBy: { autoRuleKey: 'asc' } });

describe.skipIf(!HAS_DB)('M18 stage move writes the stage auto tasks (NG-216)', () => {
  beforeAll(async () => {
    const t = await admin.tenant.create({ data: { name: `ng216-${RUN}`, slug: `ng216-${RUN}`, country: 'TR', orgType: 'CONSULTANCY' } });
    tenantId = t.id;
  });

  afterAll(async () => {
    await admin.tenant.deleteMany({ where: { slug: { endsWith: `-${RUN}` } } });
    await admin.$disconnect();
    await prisma.$disconnect();
  });

  test('ELIGIBILITY_ANALYSIS → PROPOSAL creates "send quote" and "follow up" with due dates', async () => {
    const dealId = await dealAt('ELIGIBILITY_ANALYSIS', 'proposal');
    const before = Date.now();
    await move(dealId, 'PROPOSAL');
    const tasks = await tasksOf(dealId);
    expect(tasks.map((t) => t.autoRuleKey)).toEqual(['proposal.follow-up', 'proposal.send-quote']);
    for (const t of tasks) {
      expect(t.autoGenerated).toBe(true);
      expect(t.title.length).toBeGreaterThan(0);
      expect(t.title).not.toContain('proposal.');
      expect(t.doneAt).toBeNull();
    }
    const sendQuote = tasks.find((t) => t.autoRuleKey === 'proposal.send-quote');
    const dueInMs = (sendQuote?.dueAt?.getTime() ?? 0) - before;
    expect(dueInMs).toBeGreaterThanOrEqual(2 * 24 * 3600 * 1000 - 60_000);
    expect(dueInMs).toBeLessThanOrEqual(2 * 24 * 3600 * 1000 + 60_000);
  });

  test('back and forth (PROPOSAL → ELIGIBILITY_ANALYSIS → PROPOSAL) does not duplicate tasks', async () => {
    const dealId = await dealAt('ELIGIBILITY_ANALYSIS', 'backforth');
    await move(dealId, 'PROPOSAL');
    await move(dealId, 'ELIGIBILITY_ANALYSIS');
    await move(dealId, 'PROPOSAL');
    const keys = (await tasksOf(dealId)).map((t) => t.autoRuleKey);
    expect(keys).toEqual(['eligibility.check-call-rules', 'proposal.follow-up', 'proposal.send-quote']);
  });

  test('a refused move writes no task and no stage change', async () => {
    const dealId = await dealAt('NEW', 'refused');
    await expect(move(dealId, 'PROPOSAL')).rejects.toBeInstanceOf(DealTransitionError);
    expect(await tasksOf(dealId)).toEqual([]);
    expect((await admin.deal.findUniqueOrThrow({ where: { id: dealId } })).stage).toBe('NEW');
    expect(await admin.dealActivity.count({ where: { tenantId, dealId } })).toBe(0);
  });
});
