async function seedAgencies(): Promise<AgencyFixture> {
  const stamp = `rpt-ag-${Date.now()}-${randomUUID().slice(0, 6)}`;
  const now = new Date();
  const period = reportPeriod(now);

  const { agencyA, agencyB, users } = await withSystemScope('platform-admin', 'e2e.reports-ui.agency.setup', async (tx) => {
    const mkAgency = (key: string) =>
      tx.tenant.create({
        data: { name: `Kalkınma Ajansı ${key} ${stamp}`, slug: `${stamp}-${key}`, country: 'TR', kind: 'AGENCY' },
        select: { id: true, name: true },
      });
    const a = await mkAgency('A');
    const b = await mkAgency('B');
    const mkUser = async (key: string, tenantId: string) => {
      const u = { id: `${stamp}-${key}`, email: `${stamp}-${key}@e2e.fabrika.test`, tenantId };
      await tx.user.create({ data: { id: u.id, email: u.email, name: `AG ${key}`, locale: 'tr' } });
      await tx.membership.create({ data: { userId: u.id, tenantId, role: 'TENANT_OWNER' } });
      return u;
    };
    return {
      agencyA: a,
      agencyB: b,
      users: { a: await mkUser('a', a.id), b: await mkUser('b', b.id) },
    };
  });

  // Each agency issues a code; every organisation is opened with it, through the same
  // redeem function registration calls (one use each).
  const orgIds: string[] = [];
  const orgNames: string[] = [];
  const link = async (agencyId: string, key: string, province: string, orgType: 'SME' | 'UNIVERSITY') => {
    const { code } = await withTenant(agencyId, (tx) =>
      createInviteCodeIn(tx, {
        tenantId: agencyId,
        createdBy: users[key === 'A' ? 'a' : 'b'].id,
        expiresAt: new Date(Date.now() + 7 * 86_400_000),
        label: `reports-ui e2e ${stamp}`,
      }),
    );
    for (let i = 1; i <= LINKED_ORGS; i++) {
      const name = `Kurum ${key}${i} ${stamp}`;
      const org = await prisma.$transaction(async (tx) => {
        const redeemed = await redeemInviteCode(tx, code);
        expect(redeemed, `invite code of agency ${key} must redeem`).toBe(agencyId);
        return tx.tenant.create({
          data: { name, slug: `${stamp}-${key}${i}`, country: 'TR', orgType, province, agencyId: redeemed! },
          select: { id: true },
        });
      });
      orgIds.push(org.id);
      orgNames.push(name);
    }
  };
  await link(agencyA.id, 'A', 'Kütahya', 'SME');
  await link(agencyB.id, 'B', 'Bartın', 'UNIVERSITY');

  // A user of one of agency A's own member organisations: a normal tenant.
  const orgUser = await withSystemScope('platform-admin', 'e2e.reports-ui.agency.setup', async (tx) => {
    const u = { id: `${stamp}-org`, email: `${stamp}-org@e2e.fabrika.test`, tenantId: orgIds[0]! };
    await tx.user.create({ data: { id: u.id, email: u.email, name: 'AG org', locale: 'tr' } });
    await tx.membership.create({ data: { userId: u.id, tenantId: u.tenantId, role: 'TENANT_OWNER' } });
    return u;
  });

  // The monthly job, limited to these two agencies.
  const run = await generateAgencyReports(period, now, { agencies: async () => [{ id: agencyA.id }, { id: agencyB.id }] });
  expect(run).toMatchObject({ agencies: 2, generated: 2, failed: 0 });

  const ids = await withSystemScope('platform-admin', 'e2e.reports-ui.agency.setup', (tx) =>
    tx.auditEvent.findMany({
      where: { tenantId: { in: [agencyA.id, agencyB.id] }, type: 'agency.report.generated' },
      select: { id: true, tenantId: true },
    }),
  );
  const reportA = ids.find((r) => r.tenantId === agencyA.id)!.id;
  const reportB = ids.find((r) => r.tenantId === agencyB.id)!.id;

  return { stamp, period, agencyA, agencyB, orgIds, orgNames, users: { ...users, org: orgUser }, reportA, reportB };
}

async function cleanupAgencies(f: AgencyFixture | undefined) {
  if (!f) return;
  await withSystemScope('platform-admin', 'e2e.reports-ui.agency.cleanup', async (tx) => {
    const tenants = [...f.orgIds, f.agencyA.id, f.agencyB.id];
    await tx.membership.deleteMany({ where: { tenantId: { in: tenants } } });
    await tx.user.deleteMany({ where: { id: { startsWith: requireId(f.stamp, 'stamp') } } });
    await tx.auditEvent.deleteMany({ where: { tenantId: { in: tenants } } });
    await tx.agencyInviteCode.deleteMany({ where: { tenantId: { in: [f.agencyA.id, f.agencyB.id] } } });
    await tx.tenant.deleteMany({ where: { id: { in: presentIds(f.orgIds) } } });
    await tx.tenant.deleteMany({ where: { id: { in: [f.agencyA.id, f.agencyB.id] } } });
  });
}

