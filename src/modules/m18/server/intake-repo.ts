import { createTranslator } from 'next-intl';
import { Prisma } from '@prisma/client';

import {
  LEAD_INTAKE_CREATED_EVENT,
  leadIntakeSourceRef,
  type LeadIntakeCreatedEvent,
  type LeadIntakeIds,
  type LeadIntakePort,
  type LeadIntakeRequest,
  type LeadIntakeResult,
} from '@/core/contracts/lead-intake';
import { eventBus, type EventBus } from '@/core/events';
import { prisma, withTenantOn, type TenantTx } from '@/lib/db';
import { logger } from '@/lib/logger';
import enMessages from '../../../../messages/en.json';
import trMessages from '../../../../messages/tr.json';
import { dedupeKey } from './duplicates';
import { checkIntakeConsent, isIntakeTenant, parseIntakeRequest } from './intake';
import { autoTasksForStage } from './pipeline-rules';
import { plateForProvince } from './taxonomy';

/**
 * NG-138 (M18-F4) — the M18 consumer of the lead intake contract. One accepted request
 * becomes, inside the target tenant and in ONE transaction: a LeadOrganization, a
 * LeadContact, a Deal at the first stage, its first DealTask, a FORM DealActivity and the
 * `Consent` row that proves the transfer was agreed to.
 *
 * The visitor is referenced, not copied twice: every row carries
 * `sourceRef = public-lead:<publicLeadId>`, the platform keeps the contact request itself.
 * Retried requests are idempotent through the (tenantId, sourceRef) unique indexes.
 * Nothing here logs a name, address or organisation.
 */

const MESSAGES = { tr: trMessages, en: enMessages } as const;

function intakeTranslator(locale: string) {
  const l = locale === 'en' ? 'en' : 'tr';
  return createTranslator({ locale: l, messages: MESSAGES[l], namespace: 'm18.intake' });
}

/** `Consent.userId` of a visitor who has no account. Not a foreign key (see the model). */
export function leadIntakeConsentSubject(publicLeadId: string): string {
  return `public-lead:${publicLeadId}`;
}

async function findLanded(tx: TenantTx, tenantId: string, sourceRef: string): Promise<LeadIntakeIds | null> {
  const deal = await tx.deal.findFirst({
    where: { tenantId, sourceRef },
    select: { id: true, organizationId: true, primaryContactId: true },
  });
  if (!deal?.primaryContactId) return null;
  const task = await tx.dealTask.findFirst({ where: { tenantId, sourceRef }, select: { id: true } });
  if (!task) return null;
  return { organizationId: deal.organizationId, contactId: deal.primaryContactId, dealId: deal.id, taskId: task.id };
}

/** The write itself; the caller owns the tenant transaction. */
export async function acceptLeadIntake(tx: TenantTx, request: LeadIntakeRequest): Promise<LeadIntakeResult> {
  const consentRefusal = checkIntakeConsent(request.consent);
  if (consentRefusal) return { status: 'refused', reason: consentRefusal };
  const consent = request.consent!;

  const data = parseIntakeRequest(request);
  if (!data) return { status: 'refused', reason: 'invalid' };

  const tenantId = data.targetTenantId;
  const tenant = await tx.tenant.findFirst({
    where: { id: tenantId },
    select: { orgType: true, kind: true, deletedAt: true, locale: true },
  });
  if (!tenant) return { status: 'refused', reason: 'tenant_not_found' };
  if (!isIntakeTenant(tenant)) return { status: 'refused', reason: 'tenant_ineligible' };

  const sourceRef = leadIntakeSourceRef(data.publicLeadId);
  const landed = await findLanded(tx, tenantId, sourceRef);
  if (landed) return { status: 'duplicate', ids: landed };

  const t = intakeTranslator(tenant.locale);
  const provinceCode = data.organisation.province ? plateForProvince(data.organisation.province) : null;

  const organization = await tx.leadOrganization.create({
    data: {
      tenantId,
      name: data.organisation.name,
      provinceCode,
      district: data.organisation.district,
      dedupeKey: dedupeKey({ name: data.organisation.name, provinceCode }),
      sourceRef,
    },
    select: { id: true },
  });
  const contact = await tx.leadContact.create({
    data: {
      tenantId,
      organizationId: organization.id,
      fullName: data.contact.fullName,
      email: data.contact.email,
      sourceRef,
    },
    select: { id: true },
  });
  const deal = await tx.deal.create({
    data: {
      tenantId,
      organizationId: organization.id,
      primaryContactId: contact.id,
      title: t('dealTitle', { organisation: data.organisation.name }),
      stage: 'NEW',
      sourceRef,
    },
    select: { id: true },
  });

  const planned = autoTasksForStage('NEW', data.receivedAt, [])[0];
  const task = await tx.dealTask.create({
    data: {
      tenantId,
      dealId: deal.id,
      title: t('firstContactTask'),
      dueAt: planned?.dueAt ?? null,
      autoGenerated: planned !== undefined,
      autoRuleKey: planned?.autoRuleKey ?? null,
      sourceRef,
    },
    select: { id: true },
  });

  if (data.readiness) {
    await tx.dealActivity.create({
      data: {
        tenantId,
        dealId: deal.id,
        kind: 'FORM',
        payload: { publicLeadId: data.publicLeadId, readinessCode: data.readiness.code },
        note: t('activityNote', { total: data.readiness.total, level: data.readiness.level }),
        occurredAt: data.receivedAt,
        sourceRef,
      },
    });
  }

  await tx.consent.create({
    data: {
      tenantId,
      userId: leadIntakeConsentSubject(data.publicLeadId),
      kind: 'EXPLICIT_CONSENT',
      purpose: 'LEAD_INTAKE',
      documentId: consent.documentId,
      documentVersion: consent.documentVersion,
      locale: consent.locale,
      grantedAt: consent.grantedAt,
    },
  });

  return {
    status: 'created',
    ids: { organizationId: organization.id, contactId: contact.id, dealId: deal.id, taskId: task.id },
  };
}

/** The port M18 exposes: one tenant transaction per request, a lost insert race reads back as a duplicate. */
export function createLeadIntakePort(db: typeof prisma = prisma, bus: EventBus = eventBus): LeadIntakePort {
  return {
    async accept(request) {
      const tenantId = typeof request.targetTenantId === 'string' ? request.targetTenantId : '';
      if (!tenantId) return { status: 'refused', reason: 'invalid' };
      try {
        const result = await withTenantOn(db, tenantId, (tx) => acceptLeadIntake(tx, request));
        // After the commit; a failing listener never undoes or fails the intake.
        if (result.status === 'created') {
          const event: LeadIntakeCreatedEvent = {
            name: LEAD_INTAKE_CREATED_EVENT,
            payload: { publicLeadId: request.publicLeadId, tenantId, ids: result.ids, ownerUserId: null },
            occurredAt: new Date(),
          };
          await bus.publish(event);
        }
        return result;
      } catch (error) {
        if (error instanceof Prisma.PrismaClientKnownRequestError && error.code === 'P2002') {
          const landed = await withTenantOn(db, tenantId, (tx) =>
            findLanded(tx, tenantId, leadIntakeSourceRef(request.publicLeadId))
          );
          if (landed) return { status: 'duplicate', ids: landed };
        }
        // The error's name only: a Prisma message can quote the values it failed on.
        logger.error('lead intake failed', { error: error instanceof Error ? error.name : 'unknown' });
        throw error;
      }
    },
  };
}
