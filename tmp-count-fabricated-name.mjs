import fs from 'node:fs';
import pg from 'pg';
const url = fs.readFileSync('.env','utf8').match(/^DATABASE_URL=(.*)$/m)[1].replace(/^["']|["']$/g,'');
const c = new pg.Client({ connectionString: url });
await c.connect();
console.log('--- Workspace ---');
console.table((await c.query('select id, slug, "tenantId" from "Workspace" limit 5')).rows);
console.log('--- Opportunity ---');
console.table((await c.query('select id, "tenantId", title from "Opportunity" limit 5')).rows);
console.log('--- Membership (demo-user-alice) ---');
console.table((await c.query('select "userId","tenantId",role,"workspaceIds" from "Membership" limit 5')).rows);
await c.end();
