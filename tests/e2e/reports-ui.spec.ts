/**
 * TASK-MUU76X5ZX1RQS (FB E2E-GAP-6) — the report screens with real data.
 *
 * Until now the report screens were only tested for "shows no invented data when empty"
 * (fabricated-fallbacks.spec.ts, one 40-hour row). This spec checks what a user sees
 * when there IS data:
 *
 *   a. /[workspace]/reports/person-days — several opportunities, users and days, one
 *      soft-deleted row and another tenant's row. Every number on the page must equal
 *      the number computed HERE from the seed (EXPECTED below), not from the product's
 *      own helpers. Then a user logs effort through the opportunity's effort tab and the
 *      report follows it. The report has no filter or date range (there is none to test).
 *   b. /ajans — an AGENCY tenant with organisations linked through its invite code
 *      (createInviteCodeIn + redeemInviteCode, the registration path's own functions),
 *      and the monthly report generated by the job function. The panel lists the report.
 *      The report is opened on screen from the panel (NG-341: never a file — no CSV, no
 *      print/PDF, no download link) and its content is parsed: the right agency and
 *      province, and nothing of a second agency. The old CSV address is a 404.
 *   c. The report route refuses everyone else: anonymous 401, a non-agency
 *      tenant (one of the agency's own member organisations) 403, a second agency 404.
 *   d. Both screens in EN at 390 px.
 *
 * Every identity is minted per test (seed in beforeEach, delete in afterEach), so
 * `--repeat-each` runs never share rows. demo-tenant is never touched. Session cookies
 * are minted, not typed into the demo form, so the spec also runs under `next start`.
 */

const COOKIE_NAME = 'authjs.session-token';
const SECRET = e2eAuthSecret();
