    // Log 13 h on Gamma through the effort tab, the way a user does.
    await page.getByRole('link', { name: TITLES.gamma }).click();
    await page.waitForURL(new RegExp(`/${f!.oppIds.gamma}$`));
    await page.getByRole('button', { name: /Efor/ }).click();
