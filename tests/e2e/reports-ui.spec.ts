async function seedPersonDays(): Promise<PdFixture> {
  const stamp = `rpt-pd-${Date.now()}-${randomUUID().slice(0, 6)}`;
  const workspaceSlug = `${stamp}-ws`;
  return withSystemScope('platform-admin', 'e2e.reports-ui.person-days.setup', async (tx) => {
    const mkTenant = (suffix: string) =>
      tx.tenant.create({
        data: { name: `Reports PD ${suffix} ${stamp}`, slug: `${stamp}-${suffix}`, country: 'TR', orgType: 'SME' },
      });
    const tenant = await mkTenant('own');
    const foreign = await mkTenant('foreign');
    for (const t of [tenant, foreign]) {
      // M5 is in every plan; `ultra` keeps the gate out of the picture. The tenant's own
      // switch is set explicitly, so the spec does not read whatever a default says.
      await tx.subscription.create({ data: { tenantId: t.id, planId: 'ultra', status: 'ACTIVE' } });
      await tx.moduleState.create({
        data: { tenantId: t.id, moduleId: 'M5', status: 'ON', changedBy: 'reports-ui e2e fixture' },
      });
    }
    const ws = await tx.workspace.create({ data: { tenantId: tenant.id, name: 'Reports PD', slug: workspaceSlug } });
    const fws = await tx.workspace.create({
      data: { tenantId: foreign.id, name: 'Reports PD foreign', slug: `${workspaceSlug}-f` },
    });

    const users: Record<'u1' | 'u2' | 'f', { id: string; email: string }> = {
      u1: { id: `${stamp}-u1`, email: `${stamp}-u1@e2e.fabrika.test` },
      u2: { id: `${stamp}-u2`, email: `${stamp}-u2@e2e.fabrika.test` },
      f: { id: `${stamp}-f`, email: `${stamp}-f@e2e.fabrika.test` },
    };
    for (const [key, u] of Object.entries(users)) {
      await tx.user.create({ data: { id: u.id, email: u.email, name: `PD ${key}`, locale: 'tr' } });
      const own = key !== 'f';
      await tx.membership.create({
        data: {
          userId: u.id,
          tenantId: own ? tenant.id : foreign.id,
          role: 'TENANT_OWNER',
          workspaceIds: [own ? ws.id : fws.id],
        },
      });
    }

    const oppIds = {} as Record<OppKey, string>;
    for (const key of Object.keys(TITLES) as OppKey[]) {
      const o = await tx.opportunity.create({
        data: { tenantId: tenant.id, workspaceId: ws.id, title: TITLES[key], stage: 'G1' },
      });
      oppIds[key] = o.id;
    }
    const foreignOpp = await tx.opportunity.create({
      data: { tenantId: foreign.id, workspaceId: fws.id, title: `Foreign opportunity ${stamp}`, stage: 'G1' },
    });

    for (const [opp, user, day, hours] of EFFORT_SEED) {
      await tx.effort.create({
        data: {
          tenantId: tenant.id,
          opportunityId: oppIds[opp as OppKey],
          userId: users[user].id,
          date: new Date(`${day}T00:00:00.000Z`),
          hours,
        },
      });
    }
    await tx.effort.create({
      data: {
        tenantId: tenant.id,
        opportunityId: oppIds.beta,
        userId: users.u2.id,
        date: new Date('2026-09-06T00:00:00.000Z'),
        hours: DELETED_HOURS,
        deletedAt: new Date(),
        deletionReason: 'reports-ui e2e: must not be counted',
      },
    });
    await tx.effort.create({
      data: {
        tenantId: foreign.id,
        opportunityId: foreignOpp.id,
        userId: users.f.id,
        date: new Date('2026-09-01T00:00:00.000Z'),
        hours: FOREIGN_HOURS,
      },
    });

    return { stamp, tenantId: tenant.id, foreignTenantId: foreign.id, workspaceSlug, u1: users.u1, oppIds };
  });
}

async function cleanupPersonDays(f: PdFixture | undefined) {
  if (!f) return;
  const tenants = [f.tenantId, f.foreignTenantId];
  await withSystemScope('platform-admin', 'e2e.reports-ui.person-days.cleanup', async (tx) => {
    await tx.effort.deleteMany({ where: { tenantId: { in: tenants } } });
    await tx.opportunity.deleteMany({ where: { tenantId: { in: tenants } } });
    await tx.membership.deleteMany({ where: { tenantId: { in: tenants } } });
    await tx.moduleState.deleteMany({ where: { tenantId: { in: tenants } } });
    await tx.subscription.deleteMany({ where: { tenantId: { in: tenants } } });
    await tx.workspace.deleteMany({ where: { tenantId: { in: tenants } } });
    await tx.user.deleteMany({ where: { id: { startsWith: requireId(f.stamp, 'stamp') } } });
    await tx.tenant.deleteMany({ where: { id: { in: tenants } } });
  });
}

/** The report table as the user sees it: [title, hours, person-days] per row. */
async function readReportTable(page: Page) {
  const rows = page.locator('table tbody tr');
  const out: { title: string; hours: string; pd: string }[] = [];
  for (let i = 0; i < (await rows.count()); i++) {
    const cells = rows.nth(i).locator('td');
    out.push({
      title: (await cells.nth(0).innerText()).trim(),
      hours: (await cells.nth(1).innerText()).trim(),
      pd: (await cells.nth(2).innerText()).trim(),
    });
  }
  return out;
}

async function expectReportMatches(page: Page, expected: ReturnType<typeof expectedRows>, en: boolean) {
  await expect(page.locator('table tbody tr')).toHaveCount(expected.length);
  const shown = await readReportTable(page);
  expect(shown).toEqual(expected.map((r) => ({ title: r.title, hours: String(r.hours), pd: r.pd })));
  const total = expected.reduce((n, r) => n + r.hours, 0);
  const totalText = en
    ? `Total: ${total} hours (${(total / 8).toFixed(1)} PDs)`
    : `Toplam: ${total} saat (${(total / 8).toFixed(1)} AG)`;
  await expect(page.getByText(totalText, { exact: true })).toBeVisible();
}

