    await expect(page.getByTestId('effort-error')).toHaveCount(0);

    await page.goto(url);
    const after = expectedRows({ gamma: 13 });
    // Gamma (16 h) now sits between Alpha (20) and Beta (15.5): the order follows the data.
    expect(after.map((r) => r.title)).toEqual([TITLES.alpha, TITLES.gamma, TITLES.beta]);
    await expectReportMatches(page, after, false);
    await shot(page, 'a2-person-days-after-ui-log-tr');

