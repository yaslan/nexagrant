import { getTranslations } from 'next-intl/server';
import { withTenant } from '@/lib/db';
import { requireTenantPageRole } from '@/lib/page-role';
import { moduleGate } from '@/lib/modules/guard';
import { asRole, can } from '@/lib/rbac';
import { listDealsByStage } from '@/modules/m18/server/deals-repo';
import { listTasks } from '@/modules/m18/server/tasks-repo';
import { SectionNav } from '../_components/section-nav';
import { TaskCreateForm, TaskToggle } from '../_components/client-forms';

export default async function TasksPage({
  params,
}: {
  params: Promise<{ locale: string; workspace: string }>;
}) {
  const { locale, workspace } = await params;
  const locked = await moduleGate('M18', locale);
  if (locked) return locked;
  const { tenantId, role } = await requireTenantPageRole(locale, 'client_pipeline_read');
  const canWrite = can(asRole(role), 'client_pipeline_write');
  const t = await getTranslations({ locale, namespace: 'm18' });

  const { tasks, openDeals } = await withTenant(tenantId, async (tx) => {
    const [taskRows, board] = await Promise.all([listTasks(tx, tenantId), listDealsByStage(tx, tenantId)]);
    const open = board
      .filter((c) => c.stage !== 'WON' && c.stage !== 'REJECTED' && c.stage !== 'LOST')
      .flatMap((c) => c.deals.map((d) => ({ id: d.id, title: d.title })));
    return { tasks: taskRows, openDeals: open };
  });

  return (
    <main className="space-y-6 p-6">
      <h1 className="text-2xl font-semibold">{t('tasks.heading')}</h1>
      <SectionNav locale={locale} workspace={workspace} active="tasks" />

      {canWrite && openDeals.length > 0 ? (
        <section aria-labelledby="new-task-heading" className="space-y-2">
          <h2 id="new-task-heading" className="text-base font-semibold">{t('tasks.newTask')}</h2>
          <TaskCreateForm deals={openDeals} />
        </section>
      ) : null}

      {tasks.length === 0 ? (
        <p className="text-slate-600">{t('tasks.empty')}</p>
      ) : (
        <div className="overflow-x-auto">
          <table className="min-w-full text-left text-sm">
            <caption className="sr-only">{t('tasks.heading')}</caption>
            <thead>
              <tr className="border-b border-slate-300">
                <th scope="col" className="py-2 pr-4">{t('tasks.colTask')}</th>
                <th scope="col" className="py-2 pr-4">{t('tasks.colDeal')}</th>
                <th scope="col" className="py-2 pr-4">{t('tasks.colDue')}</th>
                <th scope="col" className="py-2 pr-4">{t('tasks.colStatus')}</th>
                <th scope="col" className="py-2" />
              </tr>
            </thead>
            <tbody>
              {tasks.map((task) => (
                <tr key={task.id} className="border-b border-slate-100 align-top">
                  <td className="py-2 pr-4 font-medium">
                    {task.title}
                    {task.autoGenerated ? <span className="ml-2 text-xs text-slate-600">{t('tasks.auto')}</span> : null}
                  </td>
                  <td className="py-2 pr-4">{task.deal.title}</td>
                  <td className="py-2 pr-4">
                    {task.dueAt ? new Intl.DateTimeFormat(locale, { dateStyle: 'medium' }).format(task.dueAt) : '—'}
                  </td>
                  <td className="py-2 pr-4">{task.doneAt ? t('tasks.done') : t('tasks.open')}</td>
                  <td className="py-2">
                    {canWrite ? <TaskToggle taskId={task.id} done={task.doneAt !== null} /> : null}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </main>
  );
}
