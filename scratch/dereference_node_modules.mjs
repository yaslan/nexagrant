import fs from 'node:fs';
import path from 'node:path';

// ESM has no __dirname; Node 20.11+ exposes the same value here.
const scriptDir = import.meta.dirname;

const targetDir = path.resolve(scriptDir, '../.next/standalone/node_modules');

console.log('Resolving symlinks in:', targetDir);

function fixSymlinks(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isSymbolicLink()) {
      try {
        const realPath = fs.realpathSync(fullPath);
        fs.unlinkSync(fullPath);
        const stat = fs.statSync(realPath);
        if (stat.isDirectory()) {
          fs.cpSync(realPath, fullPath, { recursive: true, dereference: true });
          console.log(`Converted directory symlink: ${entry.name} -> real folder`);
        } else {
          fs.copyFileSync(realPath, fullPath);
          console.log(`Converted file symlink: ${entry.name} -> real file`);
        }
      } catch (err) {
        console.error(`Failed to dereference symlink ${fullPath}:`, err instanceof Error ? err.message : err);
      }
    } else if (entry.isDirectory()) {
      fixSymlinks(fullPath);
    }
  }
}

fixSymlinks(targetDir);
console.log('Finished dereferencing all symlinks!');
